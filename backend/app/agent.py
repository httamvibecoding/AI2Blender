import re
from typing import Any

from .schemas import SceneSpec


def plan_scene(prompt: str) -> dict[str, Any]:
    """Deterministic prompt-to-spec baseline with simple multi-shot detection."""
    text = " ".join(prompt.strip().split())
    lower = text.lower()

    duration_match = re.search(r"\b(\d{1,2})\s*(?:s|sec|second|seconds|giây)\b", lower)
    duration = int(duration_match.group(1)) if duration_match else 8
    duration = min(max(duration, 2), 30)

    shot_hint = "wide" if any(word in lower for word in ("toàn cảnh", "wide", "establishing")) else "medium"
    if any(word in lower for word in ("cận", "close-up", "close up", "portrait")):
        shot_hint = "close"

    movement = "slow_push_in" if any(word in lower for word in ("tiến gần", "zoom in", "push in", "dolly")) else "static"
    emotion = "majestic and calm" if any(word in lower for word in ("uy nghi", "majestic", "trang nghiêm")) else "warm and dignified"

    action = "wave"
    if any(word in lower for word in ("cúi", "bow")):
        action = "bow"
    elif any(word in lower for word in ("chào", "greet", "salute", "xin chào")):
        action = "salute"
    elif any(word in lower for word in ("gật", "nod", "nghiêng")):
        action = "nod"
    elif any(word in lower for word in ("quay", "turn", "xoay")):
        action = "turn"
    elif any(word in lower for word in ("chỉ", "point", "hướng")):
        action = "point"

    title = text[:157] + "..." if len(text) > 160 else text
    base = {
        "title": title,
        "style": "3D cartoon, soft shapes, warm cinematic lighting",
        "scene": {"duration_seconds": duration, "fps": 24},
        "camera": {"shot": shot_hint, "movement": movement},
        "animation": {"action": action, "emotion": emotion},
        "output": {"resolution": [1280, 720], "format": "mp4"},
        "transition": "cut",
    }

    if any(word in lower for word in ("nhiều cảnh", "multi-shot", "multi shot", "shots", "chuyển cảnh", "sequence")):
        shots = [
            {**base, "title": f"{title} — establishing"},
            {**base, "title": f"{title} — close action", "camera": {"shot": "close", "movement": "static"}, "scene": {"duration_seconds": min(6, duration), "fps": 24}},
        ]
        spec = SceneSpec.model_validate({"title": title, "shots": shots, "transition": "cut"})
    else:
        spec = SceneSpec.model_validate(base)

    return {
        "spec": spec.model_dump(),
        "notes": [
            "Generated by the built-in deterministic planner; no external LLM is configured.",
            "The current Blender worker supports multiple motion actions and multi-shot sequences within one render pass.",
        ],
    }
